"""Render device configs and the containerlab topology from the SoT.

Rendering is a pure function of the SoT: same input, byte-identical output.
That is what makes the committed files under configs/ and clab/ usable as
golden files - CI re-renders and fails if the result differs.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined

from .model import Sot

ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = ROOT / "templates"

# containerlab kind and image per platform. cEOS is not on a public registry:
# import it locally first (see docs/day0-bootstrap.md).
CLAB_KIND = {
    "eos": {"kind": "arista_ceos", "image": "ceos:4.32.0F"},
    "linux": {"kind": "linux", "image": "ghcr.io/srl-labs/network-multitool"},
}

GENERATED_HEADER = "# GENERATED by netauto from the Source of Truth - do not edit by hand\n"


def _ifnum(name: str) -> int:
    return int(re.search(r"\d+$", name).group())


def device_context(sot: Sot, name: str) -> dict:
    """Everything the EOS template needs for one router, derived from the SoT."""
    dev = sot.devices[name]
    interfaces, neighbors, networks = [], [], [str(dev.loopback0.network)]
    for local, remote in sorted(sot.links_of(name), key=lambda pair: _ifnum(pair[0].interface)):
        peer = sot.devices[remote.device]
        interfaces.append(
            {
                "name": local.interface,
                "ip": str(local.ip),
                "description": f"to {remote.device}:{remote.interface}",
            }
        )
        if peer.is_router:
            neighbors.append(
                {"ip": str(remote.ip.ip), "remote_as": peer.asn, "description": remote.device}
            )
        else:
            # Host-facing subnets are originated by the leaf they hang off.
            networks.append(str(local.ip.network))
    uplinks = sum(
        1 for _, remote in sot.links_of(name) if sot.devices[remote.device].role == "spine"
    )
    return {
        "name": name,
        "asn": dev.asn,
        "router_id": str(dev.loopback0.ip),
        "loopback0": str(dev.loopback0),
        "interfaces": interfaces,
        "neighbors": neighbors,
        "networks": networks,
        "max_paths": max(1, uplinks),
    }


def render_configs(sot: Sot) -> dict[str, str]:
    """Router name -> full rendered configuration text."""
    env = Environment(
        loader=FileSystemLoader(TEMPLATES),
        undefined=StrictUndefined,  # a missing variable is an error, never an empty string
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )
    template = env.get_template("eos.j2")
    return {
        name: template.render(device_context(sot, name))
        for name, dev in sot.devices.items()
        if dev.is_router
    }


class _IndentedDumper(yaml.SafeDumper):
    """Indent list items under their key, the way people write YAML by hand."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def _clab_ifname(interface: str) -> str:
    """containerlab names every data interface ethN (Ethernet1 -> eth1)."""
    return f"eth{_ifnum(interface)}"


def render_clab(sot: Sot) -> str:
    """The containerlab topology file, so cabling has a single source."""
    nodes = {}
    for name, dev in sorted(sot.devices.items()):  # sorted: output must not depend on input order
        node = {"kind": CLAB_KIND[dev.platform]["kind"], "mgmt-ipv4": str(dev.mgmt_ip)}
        if dev.role == "host":
            ((local, remote),) = sot.links_of(name)
            node["exec"] = [
                f"ip addr add {local.ip} dev {local.interface}",
                f"ip route add {sot.supernet} via {remote.ip.ip}",
            ]
        nodes[name] = node
    links = sorted(
        (
            {
                "endpoints": [
                    f"{link.a.device}:{_clab_ifname(link.a.interface)}",
                    f"{link.b.device}:{_clab_ifname(link.b.interface)}",
                ]
            }
            for link in sot.links
        ),
        key=lambda item: item["endpoints"],
    )
    kinds = {v["kind"]: {"image": v["image"]} for v in CLAB_KIND.values()}
    topology = {
        "name": "netauto",
        "topology": {"kinds": kinds, "nodes": nodes, "links": links},
    }
    return GENERATED_HEADER + yaml.dump(topology, Dumper=_IndentedDumper, sort_keys=False)


def render_all(sot: Sot) -> dict[Path, str]:
    """Repo-relative path -> content for every generated file."""
    files = {Path("configs") / f"{name}.cfg": text for name, text in render_configs(sot).items()}
    files[Path("clab") / "lab.clab.yml"] = render_clab(sot)
    return files


def stale_files(sot: Sot, root: Path = ROOT) -> list[Path]:
    """Generated files whose committed content differs from a fresh render."""
    stale = []
    for path, content in render_all(sot).items():
        target = root / path
        if not target.exists() or target.read_text() != content:
            stale.append(path)
    # A config left behind for a device that is no longer in the SoT is stale too.
    expected = {p.name for p in render_all(sot) if p.parent.name == "configs"}
    for extra in sorted((root / "configs").glob("*.cfg")):
        if extra.name not in expected:
            stale.append(Path("configs") / extra.name)
    return stale


def write_all(sot: Sot, root: Path = ROOT) -> list[Path]:
    files = render_all(sot)
    for path, content in files.items():
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
    expected = {p.name for p in files if p.parent.name == "configs"}
    for extra in (root / "configs").glob("*.cfg"):
        if extra.name not in expected:
            extra.unlink()
    return sorted(files)
